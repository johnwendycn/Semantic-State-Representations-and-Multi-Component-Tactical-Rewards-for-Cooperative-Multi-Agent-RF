                "    \"\"\"\n",
                "    Computes Welch's unequal variances t-test and Cohen's d effect size.\n",
                "    \"\"\"\n",
                "    t_stat, p_val = stats.ttest_ind(treatment_scores, control_scores, equal_var=False)\n",
