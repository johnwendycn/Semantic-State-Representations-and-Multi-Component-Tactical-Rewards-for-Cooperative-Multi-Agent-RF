                "        \n",
                "        # In actual GRF raw dump, extract player positions:\n",
                "        # For demonstration / standard wrapper fallback:\n",
                "        p_att = np.array([[0.2, 0.0], [0.4, 0.15], [0.4, -0.15]], dtype=np.float32)\n",
